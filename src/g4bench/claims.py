"""Render the claims register (configs/claims.yaml) with evidence status computed from measured results only."""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Any

from .config import load_yaml
from .paths import CONFIGS, REPO, RESULTS

NM = "not measured"


def _comparisons(path: Path) -> list[dict[str, str]]:
    if not path.exists() or path.stat().st_size == 0:
        return []
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def engine_ratio_status(claim: dict[str, Any], pairs: list[dict[str, str]]) -> str:
    """vLLM/SGLang output-throughput ratio from seed-paired rows of engine_comparison.csv (exact hardware only)."""
    rows = [p for p in pairs if p.get("metric") == "output_throughput" and p.get("dataset", "random") == "random"
            and p.get("osl") == "1024" and f"{p.get('isl')}x{p.get('conc')}" in claim["keys"]
            and p.get("hardware_class", "").startswith("RTX-PRO-6000") and p.get("advantage")]
    if not rows:
        return NM
    ours = [float(p["advantage"]) for p in rows]
    art = [float(p["article_advantage"]) for p in rows if p.get("article_advantage")]
    weak = any(int(float(p.get("n_paired") or 0)) < 3 for p in rows)
    s = (f"measured {len(rows)}/{len(claim['keys'])}: vLLM/SGLang {min(ours):.2f}-{max(ours):.2f}x"
         + (f" (article {min(art):.2f}-{max(art):.2f}x)" if art else ""))
    return s + (" - descriptive, n<3" if weak else "")


def status(claim: dict[str, Any], comps: list[dict[str, str]], pairs: list[dict[str, str]] | None = None) -> str:
    """Evidence status for a measurable claim from comparison.csv rows (exact hardware, baselines, vs same engine)."""
    if claim["kind"] == "measurable" and claim.get("metric") == "engine_ratio":
        return engine_ratio_status(claim, pairs or [])
    if claim["kind"] != "measurable" or claim.get("metric") == "hardware":
        return {"untestable": "untestable (see reason)", "verified-source": "verified (sources)",
                "verified-analysis": "verified (analysis)"}.get(claim["kind"], NM if claim["kind"] == "measurable" else "-")
    engines = claim["engine"] if isinstance(claim["engine"], list) else [claim["engine"]]
    metrics = claim["metric"] if isinstance(claim["metric"], list) else [claim["metric"]]
    rows = [c for c in comps if c.get("reference") in engines and c.get("metric") in metrics
            and c.get("key") in claim["keys"] and c.get("hardware_class", "").startswith("RTX-PRO-6000")]
    if not rows:
        return NM
    # One row per (engine, metric, workload): the aggregate with the most runs (a config measured in several
    # campaigns, e.g. shared-server jobs and same-GPU pairs, has one aggregate per config hash).
    best: dict[tuple, dict[str, str]] = {}
    for r in rows:
        k = (r.get("reference"), r.get("metric"), r.get("key"))
        if k not in best or int(float(r.get("n") or 0)) > int(float(best[k].get("n") or 0)):
            best[k] = r
    rows = list(best.values())
    n_total = len(claim["keys"]) * len(engines) * len(metrics)
    cls: dict[str, int] = {}
    for r in rows:
        cls[r["class"]] = cls.get(r["class"], 0) + 1
    weak = any(int(float(r.get("n") or 0)) < 3 for r in rows)
    parts = ", ".join(f"{v} {k}" for k, v in sorted(cls.items()))
    return f"measured {len(rows)}/{n_total} ({parts})" + (" - descriptive, n<3" if weak else "")


def render(claims_path: Path | None = None, comparison_csv: Path | None = None,
           engine_csv: Path | None = None) -> str:
    reg = load_yaml(claims_path or CONFIGS / "claims.yaml")
    comps = _comparisons(comparison_csv or RESULTS / "summary" / "comparison.csv")
    if engine_csv is None:
        engine_csv = (RESULTS / "summary" / "engine_comparison.csv") if comparison_csv is None else Path("/nonexistent")
    pairs = _comparisons(engine_csv)
    lines = ["# Claims register (generated by `g4bench claims` from configs/claims.yaml)", "",
             "Status is computed only from measured results in `results/` (exact hardware, baseline configs). "
             f"Measured comparison rows available: {len(comps)}.", "",
             "| id | claim | kind | status |", "|---|---|---|---|"]
    for c in reg["claims"]:
        lines.append(f"| {c['id']} | {c['text']} | {c['kind']} | {status(c, comps, pairs)} |")
    lines += ["", "## Notes", ""]
    for c in reg["claims"]:
        note = c.get("plan") or c.get("reason") or c.get("evidence")
        if note:
            lines.append(f"- **{c['id']}**: {note}")
    return "\n".join(lines) + "\n"


def write(out: Path | None = None) -> Path:
    out = out or REPO / "docs" / "CLAIMS.md"
    out.write_text(render(), encoding="utf-8", newline="\n")
    return out
