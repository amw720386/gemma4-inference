"""Render the claims register (configs/claims.yaml) with evidence status computed from measured results only."""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Any

from .config import load_yaml
from .paths import CONFIGS, REPO, RESULTS

NM = "not measured"


def _comparisons(path: Path) -> list[dict[str, str]]:
    if not path.exists() or path.stat().st_size == 0:
        return []
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def status(claim: dict[str, Any], comps: list[dict[str, str]]) -> str:
    """Evidence status for a measurable claim from comparison.csv rows (exact hardware, baselines, vs same engine)."""
    if claim["kind"] != "measurable" or claim.get("metric") in ("engine_ratio", "hardware"):
        return {"untestable": "untestable (see reason)", "verified-source": "verified (sources)",
                "verified-analysis": "verified (analysis)"}.get(claim["kind"], NM if claim["kind"] == "measurable" else "-")
    engines = claim["engine"] if isinstance(claim["engine"], list) else [claim["engine"]]
    metrics = claim["metric"] if isinstance(claim["metric"], list) else [claim["metric"]]
    rows = [c for c in comps if c.get("reference") in engines and c.get("metric") in metrics
            and c.get("key") in claim["keys"] and c.get("hardware_class", "").startswith("RTX-PRO-6000")]
    if not rows:
        return NM
    n_total = len(claim["keys"]) * len(engines) * len(metrics)
    cls: dict[str, int] = {}
    for r in rows:
        cls[r["class"]] = cls.get(r["class"], 0) + 1
    weak = any(int(float(r.get("n") or 0)) < 3 for r in rows)
    parts = ", ".join(f"{v} {k}" for k, v in sorted(cls.items()))
    return f"measured {len(rows)}/{n_total} ({parts})" + (" - descriptive, n<3" if weak else "")


def render(claims_path: Path | None = None, comparison_csv: Path | None = None) -> str:
    reg = load_yaml(claims_path or CONFIGS / "claims.yaml")
    comps = _comparisons(comparison_csv or RESULTS / "summary" / "comparison.csv")
    lines = ["# Claims register (generated by `g4bench claims` from configs/claims.yaml)", "",
             "Status is computed only from measured results in `results/` (exact hardware, baseline configs). "
             f"Measured comparison rows available: {len(comps)}.", "",
             "| id | claim | kind | $10 budget | status |", "|---|---|---|---|---|"]
    for c in reg["claims"]:
        lines.append(f"| {c['id']} | {c['text']} | {c['kind']} | {c['budget']} | {status(c, comps)} |")
    lines += ["", "## Notes", ""]
    for c in reg["claims"]:
        note = c.get("plan") or c.get("reason") or c.get("evidence")
        if note:
            lines.append(f"- **{c['id']}**: {note}")
    return "\n".join(lines) + "\n"


def write(out: Path | None = None) -> Path:
    out = out or REPO / "docs" / "CLAIMS.md"
    out.write_text(render())
    return out
